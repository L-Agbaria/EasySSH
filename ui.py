    # Identity passwords
    def _ask_password(self, title, prompt):
        return simpledialog.askstring(title, prompt, show="*", parent=self)

    def _unlock(self, k: KeyEntry, action: str) -> bool:
        if not k.encrypted:
            return True
        while True:
            pw = self._ask_password(f"Password to {action}", f"Password for key '{k.name}':")
            if pw is None:
                return False
            if k.unlock(pw):
                return True
            messagebox.showerror("Wrong password", "Password not right. Try again.", parent=self)

    def _sel_key(self):
        sel = self.id_list.curselection()
        return self.keys[sel[0]] if sel else None

    def show_identity(self, _=None):
        k = self._sel_key()
        if not k:
            return
        if k.encrypted and not k.unlocked:  # READ -> password
            if not self._unlock(k, "read"):
                self.id_detail.set("Locked. Select again and give password.")
                self.id_list.selection_clear(0, "end")
                return
            self.fill_identities()  # refresh label + combobox
            self.id_list.selection_set(self.keys.index(k))
        pub = k.path.with_suffix(".pub")
        kt = k.identity.key_type.value if k.identity else "unknown"
        self.id_detail.set(f"Private: {k.path}\nPublic: {pub}\nType: {kt}\n"
                           f"Password: {'yes' if k.encrypted else 'no'}")

    def new_identity(self):
        name = simpledialog.askstring("New identity", "Name:", parent=self)
        if not name:
            return
        name = name.strip()
        types = [t for t in KeyType if t not in (KeyType.DSA, KeyType.UNKNOWN)]
        kt = simpledialog.askstring("Key type", f"Type ({', '.join(t.value for t in types)}):",
                                    initialvalue="ed25519", parent=self)
        if not kt:
            return
        try:
            key_type = KeyType(kt.strip())
        except ValueError:
            messagebox.showerror("Error", "Unknown key type.", parent=self)
            return
        # CREATE -> password (empty = no password)
        pw = self._ask_password("New password", "Password for new key (empty = none):")
        if pw is None:
            return
        if pw:
            again = self._ask_password("New password", "Type password again:")
            if again != pw:
                messagebox.showerror("Error", "Passwords differ. Nothing made.", parent=self)
                return
        private = self.identities_dir / name
        if private.exists() or private.with_suffix(".pub").exists():
            messagebox.showerror("Error", f"Identity '{name}' already exists.", parent=self)
            return
        try:
            self.identities_dir.mkdir(parents=True, exist_ok=True)
            subprocess.run(["ssh-keygen", "-q", "-t", key_type.value, "-C", name,
                            "-N", pw, "-f", str(private)],
                           check=True, capture_output=True, text=True)
        except subprocess.CalledProcessError as err:
            messagebox.showerror("ssh-keygen failed", err.stderr or str(err), parent=self)
            return
        self.reload()

    def delete_identity(self):
        k = self._sel_key()
        if not k:
            return
        if not messagebox.askyesno("Delete", f"Delete key '{k.name}'? Cannot undo.", parent=self):
            return
        if not self._unlock(k, "delete"):  # DELETE -> password
            return
        k.path.unlink(missing_ok=True)
        k.path.with_suffix(".pub").unlink(missing_ok=True)
        self.reload()

    def copy_pub(self):
        k = self._sel_key()
        if not k:
            return
        pub = k.path.with_suffix(".pub")
        if not pub.exists():
            if not self._unlock(k, "read"):
                return
        if pub.exists():
            self.clipboard_clear()
            self.clipboard_append(pub.read_text(encoding="utf-8").strip())
            self.status.set("Public key copied.")


