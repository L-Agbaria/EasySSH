    def reload(self):  # Extract data
        self.clusters, self.keys, self.tutorial_files = [], [], []
        msgs = []
        if self.clusters_dir.exists():
            try:
                self.clusters = get_clusters(self.clusters_dir)
            except Exception as err:
                msgs.append(f"clusters error: {err}")
        else:
            msgs.append(f"no clusters dir: {self.clusters_dir}")
        if self.identities_dir.exists():
            try:
                self.keys = scan_keys(self.identities_dir)
            except Exception as err:
                msgs.append(f"identities error: {err}")
        else:
            msgs.append(f"no identities dir: {self.identities_dir}")
        if self.tutorials_dir.exists():
            self.tutorial_files = sorted(self.tutorials_dir.rglob("*.md"))
        self.fill_tree()
        self.fill_identities()
        self.fill_tutorials()
        self.status.set(" | ".join(msgs) if msgs else
                        f"{len(self.clusters)} clusters, {len(self.keys)} identities, "
                        f"{len(self.tutorial_files)} tutorials")

    def fill_tree(self):
        self.tree.delete(*self.tree.get_children())
        self.node_map.clear()
        for cl in self.clusters:
            cl_node = self.tree.insert("", "end", text=cl.name, open=True)
            for cat in cl.categories.values():
                cat_node = None
                for srv in cat.values():
                    if cat_node is None:
                        cat_node = self.tree.insert(cl_node, "end", text=cat.name, open=True)
                    n = self.tree.insert(cat_node, "end", text=srv.name)
                    self.node_map[n] = (cl, srv)

    def _usable(self):
        return [k for k in self.keys if k.identity is not None]

    def fill_identities(self):
        names = [k.name for k in self._usable()]
        self.identity_box["values"] = [NONE_LABEL] + names
        if self.identity_var.get() not in self.identity_box["values"]:
            self.identity_var.set(NONE_LABEL)
        self.id_list.delete(0, "end")
        self.id_detail.set("")
        for k in self.keys:
            if k.encrypted and not k.unlocked:
                tag = "locked"
            else:
                tag = k.identity.key_type.value if k.identity else "?"
            self.id_list.insert("end", f"{k.name}  [{tag}]")

    def show_tutorial(self, _=None):
        sel = self.tut_list.curselection()
        if not sel:
            return
        path = self.tutorial_files[sel[0]]
        try:
            text = path.read_text(encoding="utf-8")
        except Exception as err:
            text = f"# Error\n\nCannot read `{path}`:\n\n{err}"
        self.md.render(text)

    def fill_tutorials(self):
        self.tut_list.delete(0, "end")
        for p in self.tutorial_files:
            self.tut_list.insert("end", p.stem)
        if self.tutorial_files:
            self.tut_list.selection_set(0)
            self.show_tutorial()
        else:
            self.md.render(f"# No tutorials\n\nPut `.md` files in:\n\n`{self.tutorials_dir}`\n\n"
                           "Then press **Reload**.")

    def on_select(self, _):  # Handle events
        sel = self.tree.selection()
        if sel and sel[0] in self.node_map:
            self.cur_cluster, self.cur_server = self.node_map[sel[0]]
            s = self.cur_server
            via = (f"via {s.connect_through[0]} / {s.connect_through[1]}"
                   if s.connect_through != ("", "") else "direct")
            self.info.set(f"{s.name}\n{s.hostname}:{s.port}  ({via})")
            cat = self.cur_cluster.categories.get(s.category_id)
            self._set_desc([
                ("Cluster", self.cur_cluster.name, self.cur_cluster.description),
                ("Category", cat.name if cat else s.category_id, cat.description if cat else ""),
                ("Server", s.name, s.description),
            ])
            self.generate()

