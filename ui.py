def _keygen_pub(path: Path, passphrase: str) -> str | None:
    r = subprocess.run([
            "ssh-keygen", 
            "-y", 
            "-P", passphrase, 
            "-f", str(path)],
        capture_output=True, text=True)
    return r.stdout if r.returncode == 0 else None


def _looks_private(path: Path) -> bool:
    try:
        with open(path, "r", encoding="utf-8") as f:
            return "PRIVATE KEY" in f.readline()
    except Exception:
        return False


class KeyEntry:
    def __init__(self, path: Path):
        self.path = path
        self.name = path.stem
        self.encrypted = _keygen_pub(path, "") is None
        self.unlocked = not self.encrypted  # unlocked = password given this session
        self.identity: Identity | None = None
        self._try_identity()

    def _try_identity(self):
        pub = Path(f"{self.path}.pub")
        if not pub.exists() and self.encrypted:
            return  # need password to make .pub
        try:
            self.identity = Identity(self.name, self.path)
        except Exception:
            self.identity = None

    def unlock(self, passphrase: str) -> bool:
        pub_text = _keygen_pub(self.path, passphrase)
        if pub_text is None:
            return False
        pub = Path(f"{self.path}.pub")
        if not pub.exists():
            pub.write_text(pub_text, encoding="utf-8")
        self.unlocked = True
        self._try_identity()
        return True


def scan_keys(idn_dir: Path) -> list[KeyEntry]:
    out = []
    for p in sorted(idn_dir.rglob("*")):
        if p.is_file() and p.suffix != ".pub" and _looks_private(p):
            out.append(KeyEntry(p))
    return out


